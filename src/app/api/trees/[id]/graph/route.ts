import { db } from "@/lib/supabase";
import { fail, ok } from "@/lib/api";
import type { TreeEdge, TreeNode } from "@/lib/types";

type Ctx = { params: Promise<{ id: string }> };

export async function GET(_req: Request, { params }: Ctx) {
  const { id } = await params;
  const [n, e] = await Promise.all([
    db().from("tree_nodes").select("*").eq("tree_id", id),
    db().from("tree_edges").select("*").eq("tree_id", id),
  ]);
  if (n.error) return fail(n.error);
  if (e.error) return fail(e.error);
  return ok({ nodes: n.data, edges: e.data });
}

/** Replace the whole graph of a tree. Node/edge ids are generated by the client. */
export async function PUT(request: Request, { params }: Ctx) {
  const { id } = await params;
  const { nodes, edges } = (await request.json()) as {
    nodes: Omit<TreeNode, "tree_id">[];
    edges: Omit<TreeEdge, "tree_id">[];
  };
  const del = await db().from("tree_nodes").delete().eq("tree_id", id); // cascades edges
  if (del.error) return fail(del.error);
  if (nodes.length) {
    const r = await db().from("tree_nodes").insert(
      nodes.map((nd) => ({ id: nd.id, tree_id: id, book_id: nd.book_id, x: nd.x, y: nd.y })),
    );
    if (r.error) return fail(r.error);
  }
  const ids = new Set(nodes.map((nd) => nd.id));
  const valid = edges.filter((ed) => ids.has(ed.from_node) && ids.has(ed.to_node));
  if (valid.length) {
    const r = await db().from("tree_edges").insert(
      valid.map((ed) => ({ id: ed.id, tree_id: id, from_node: ed.from_node, to_node: ed.to_node, relation: ed.relation, note: ed.note })),
    );
    if (r.error) return fail(r.error);
  }
  return ok({ ok: true });
}
